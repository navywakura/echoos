Icon* get_app_icon(Icon *app_custom_icon) {
    /* Si la app no tiene icono o el puntero es nulo, usa default_file.png */
    if (app_custom_icon == NULL || app_custom_icon->pixel_data == NULL) {
        return &g_default_icon;
    }
    return app_custom_icon;
}

void draw_app_tile(uint32_t x, uint32_t y, const char *title, Icon *custom_icon) {
    Icon *icon_to_render = get_app_icon(custom_icon);
    
    /* Renderizado directo sobre Framebuffer estático */
    fb_round_blend(x, y, 76, 76, 6, 0x0012141C, 180);
    fb_rect_outline(x, y, 76, 76, 0x0000FF9D);

    uint32_t off_x = x + (76 - icon_to_render->width) / 2;
    uint32_t off_y = y + 8;
    for (uint32_t iy = 0; iy < icon_to_render->height; iy++) {
        for (uint32_t ix = 0; ix < icon_to_render->width; ix++) {
            uint32_t pixel = icon_to_render->pixel_data[iy * icon_to_render->width + ix];
            uint8_t a = (pixel >> 24) & 0xff;
            if (a > 20) {
                fb_pixel(off_x + ix, off_y + iy, pixel & 0x00ffffff);
            }
        }
    }

    if (title) {
        uint32_t tw = (uint32_t)k_strlen(title) * FB_GLYPH_W;
        uint32_t tx = (tw < 76) ? (x + (76 - tw) / 2) : x;
        fb_text(tx, y + 54, title, 0x0000E5FF, 0x0012141C);
    }
}
