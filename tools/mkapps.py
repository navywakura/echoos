#!/usr/bin/env python3
"""RXos — embed userland/apps/*.rxc into a C header (userland/apps/apps.h).

The kernel has no loader for external files at boot, so the built-in Roxenite
apps are compiled in. The .rxc files in userland/apps/ are the canonical
sources; this script regenerates the header (which is committed, like
font8x16.h, so the kernel builds without Python).

Usage:  python3 tools/mkapps.py
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APPS = os.path.join(ROOT, "userland", "apps")
OUT  = os.path.join(APPS, "apps.h")

def c_escape(data: str) -> str:
    lines = []
    for ln in data.split("\n"):
        esc = ln.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{esc}\\n"')
    return "\n".join(lines)

def main():
    rxc = sorted(f for f in os.listdir(APPS) if f.endswith(".rxc"))
    if not rxc:
        sys.exit("no .rxc files found")
    with open(OUT, "w") as o:
        o.write("/* GENERATED by tools/mkapps.py from the .rxc files in userland/apps/.\n"
                " * Do not edit. Regenerate with:  make apps  (python3 tools/mkapps.py) */\n"
                "#ifndef RXOS_APPS_H\n#define RXOS_APPS_H\n\n"
                "typedef struct { const char *name; const char *source; } rxos_builtin_app;\n\n")
        for f in rxc:
            sym = f.replace(".", "_").upper()
            src = open(os.path.join(APPS, f)).read().rstrip("\n")
            o.write(f"static const char APP_{sym}[] =\n{c_escape(src)};\n\n")
        o.write("static const rxos_builtin_app RXOS_BUILTIN_APPS[] = {\n")
        for f in rxc:
            sym = f.replace(".", "_").upper()
            o.write(f'    {{ "{f}", APP_{sym} }},\n')
        o.write("};\n#define RXOS_BUILTIN_APP_COUNT "
                f"{len(rxc)}\n\n#endif /* RXOS_APPS_H */\n")
    print(f"[mkapps] wrote {OUT} ({len(rxc)} apps)")

if __name__ == "__main__":
    main()
